let _cartAutoId = 1;
const _cart = [];

export const cartDB = {
  list() {
    return _cart.map((c) => ({ ...c }));
  },
  add(product, quantity) {
    const found = _cart.find((c) => c.product.id === product.id);
    if (found) {
      found.quantity += quantity ?? 1;
      return found;
    }
    const item = { id: _cartAutoId++, product, quantity: quantity ?? 1 };
    _cart.push(item);
    return item;
  },
  update(id, quantity) {
    const it = _cart.find((c) => c.id === id);
    if (!it) return null;
    it.quantity = Math.max(1, quantity);
    return it;
  },
  remove(id) {
    const i = _cart.findIndex((c) => c.id === id);
    if (i >= 0) _cart.splice(i, 1);
  },
};
